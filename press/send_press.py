def change(code):
    global status_code
    if code == 1:
        status_code = 1
        top.config(bg='red')
    elif code == 0:
        status_code = 0
        top.config(bg='white')

def send_text():
    i = 1
    for text in press_text_list:
        if status_code == 1:
            print('禁止状态不能发送')
            return

        print('连续发送',i)
        i = i+1
        pyperclip.copy(text)
        # time.sleep(0.2)
        pyautogui.hotkey("ctrl", "a")
        pyautogui.hotkey("ctrl", "v")
        time.sleep(0.1)
        pyautogui.press('enter')
        time.sleep(0.2)
        pyautogui.press('enter')


        time.sleep(press_mode['send'])
        # time.sleep(0.7)

def start_send_F6():
    t = threading.Thread(target=send_text)
    t.start()

def stop_text():
    print('停止')
    change(1)
    time.sleep(press_mode['stop'])
    # time.sleep(1.5)
    change(0)

def reset():
    print('恢复')
    change(0)

def press_F7():
    t = threading.Thread(target=stop_text)
    t.start()

l1 = Label(top,text=f'F6发送 F7停止 当前{press_mode["mode"]}')
